// 駅の位置（緯度・経度）からおおまかなエリアを決める。境界付近の誤差は、
// 路線を「駅が 1 つでもあるエリアすべて」に出すことで実害を減らす（build-lines.mjs）
export function regionOf(lat, lon) {
  if (lat >= 41.4) return "北海道";
  if (lat < 27.5 || (lon < 131.9 && lat < 34.0)) return "九州・沖縄";
  if (lat >= 37.0 && lon >= 139.2) return "東北";
  // 瀬戸内海は斜めなので、四国との境は海の上を通る斜めの線（呉 34.25/132.56 と今治 34.07/133.0、
  // 宇野 34.49/133.95 と坂出 34.32/133.86 の間）で分ける
  if (lat > 32.7 && lon > 132.35 && lon < 134.8 && lat < 34.15 + (lon - 132.5) * 0.159) return "四国";
  if (lon < 134.2) return "中国";
  if (lon < 136.4) return "近畿";
  if (lon >= 138.9 && lat < 37.0 && !(lat < 35.2 && lon < 139.2)) return "関東";
  return "中部";
}
